"""Plaintext baselines in sidebar order; never replace stored operator edits.

Grounded in sidebar_menu.html, urls.py and the related views/forms/templates.
Importing this module does not read or write the database.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class OperationManual:
    menu_key: str
    title: str
    url_name: str
    description: str


def _body(target: str, steps: tuple[str, ...], caution: str) -> str:
    return ('内容\n' + target + '\n\n操作手順\n'
            + '\n'.join(f'{number}. {step}' for number, step in enumerate(steps, 1))
            + '\n\n注意点\n' + caution)


